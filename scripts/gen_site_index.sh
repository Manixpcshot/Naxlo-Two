#!/usr/bin/env bash
# Regenerate the download table in site/index.html from GitHub's own release
# data — the same API the in-app updater reads.
#
# Why a script and not a hand-typed table: a stale download page is worse than no
# download page. Every link, size and checksum here is taken from the release
# asset list, so the numbers cannot drift from what the repository actually
# published. An asset the pipeline did not build becomes an explicit
# "not built yet" row instead of a 404 or a silently missing platform.
#
# Usage:
#   scripts/gen_site_index.sh              # newest published release
#   scripts/gen_site_index.sh v0.3.0       # a specific tag
#   scripts/gen_site_index.sh --check      # exit 1 if the file is out of date
set -euo pipefail

OWNER="${SITE_OWNER:-Manixpcshot}"
REPO="${SITE_REPO:-Naxlo-Two}"
FILE="site/index.html"
CHECK=0
TAG=""

for arg in "$@"; do
  case "$arg" in
    --check) CHECK=1 ;;
    v*) TAG="${arg#v}" ;;
    *) echo "usage: $0 [vX.Y.Z] [--check]" >&2; exit 2 ;;
  esac
done

command -v gh >/dev/null || { echo "need gh (GitHub CLI), authenticated for $OWNER/$REPO" >&2; exit 1; }
command -v jq >/dev/null || { echo "need jq" >&2; exit 1; }
cd "$(dirname "$0")/.."
[ -f "$FILE" ] || { echo "missing $FILE" >&2; exit 1; }

# label|platform|asset-name, in the order the app prefers them — see
# GithubReleases.assetPatterns in packages/naxlo_core/lib/src/update/github_releases.dart.
# A name absent from this list is not offered by the app either, so it must not
# appear on the site as though it were (SHA256SUMS.txt is a release asset too).
ROWS='Windows x64|windows|setup-Naxlo.x64.exe
Linux x64 · deb|linux|Naxlo.linux.x64.deb
Linux x64 · rpm|linux|Naxlo.linux.x64.rpm
Arch · pkg|linux|Naxlo.linux.x64.pkg.tar.zst
Android · arm64-v8a|android|Naxlo.android.arm64-v8a.apk
Android · universal|android|Naxlo.apk
Android · armeabi-v7a|android|Naxlo.android.armeabi-v7a.apk
Android · x86_64|android|Naxlo.android.x86_64.apk
macOS universal|macos|Naxlo.macOS.universal.dmg
Windows ARM64|windows|setup-Naxlo.arm64.exe'

if [ -n "$TAG" ]; then
  RELEASE="$(gh api "repos/$OWNER/$REPO/releases/tags/v$TAG")"
else
  # Newest by *version*, not by the API's ordering: GitHub sorts by creation date,
  # and a release created last week can carry an older version than the one
  # created before it (a rollback leaves the repo looking newer than it is).
  RELEASE="$(gh api "repos/$OWNER/$REPO/releases?per_page=30" \
    | jq -c '[.[] | select(.draft | not)]
              | max_by(.tag_name | sub("^v"; "") | split("-")[0] | split(".")
                       | map(tonumber? // 0) | (.[0] * 1000000 + .[1] * 1000 + (.[2] // 0)))')"
fi

TAG_NAME="$(jq -r '.tag_name // empty' <<<"$RELEASE")"
[ -n "$TAG_NAME" ] || { echo "no published release for $OWNER/$REPO" >&2; exit 1; }
VERSION="${TAG_NAME#v}"
ASSETS="$(jq -c '.assets // []' <<<"$RELEASE")"
echo "release: $TAG_NAME ($(jq -r '.assets | length' <<<"$RELEASE") assets)"

# The `release` manifest the app reads is the publisher's second statement about
# the same file, so the two are cross-checked — but only when the manifest
# actually describes *this* release. It is committed to `main` after the tag is
# pushed (the digests do not exist until the assets are uploaded), which means the
# copy at a tag ref still describes the previous release; comparing that against
# GitHub's digests would warn on every run forever. `--check` in ci.yml is where
# the lag becomes someone's problem, not this script's.
MANIFEST="$(gh api "repos/$OWNER/$REPO/contents/release?ref=main" --jq '.content' 2>/dev/null \
  | base64 -d 2>/dev/null || true)"
MANIFEST_VERSION="$(jq -r '.linux.stable.version // .windows.stable.version // empty' <<<"$MANIFEST" 2>/dev/null || true)"
if [ "$MANIFEST_VERSION" != "$VERSION" ]; then
  echo "note: the release manifest on main describes ${MANIFEST_VERSION:-nothing}; cross-check skipped (it lags the tag by one release)" >&2
  MANIFEST=""
fi

tmp="$(mktemp)"
out="$(mktemp)"
trap 'rm -f "$tmp" "$out"' EXIT

{
  echo '          <!-- generated by scripts/gen_site_index.sh — do not hand-edit these rows -->'
  while IFS='|' read -r label platform name; do
    [ -n "$label" ] || continue
    asset="$(jq -c --arg n "$name" '[.[] | select(.name == $n and .state == "uploaded")] | first' <<<"$ASSETS")"
    if [ "$asset" = "null" ] || [ -z "$asset" ]; then
      printf '          <tr class="dim">\n'
      printf '            <td><span class="pill na">%s</span></td>\n' "$label"
      printf '            <td class="name">%s — not built for this release</td>\n' "$name"
      printf '            <td class="sz">—</td>\n'
      printf '            <td><span class="sha">the app announces the update and hands the download to your browser</span></td>\n'
      printf '            <td></td>\n          </tr>\n'
      continue
    fi
    size="$(jq -r '.size // 0' <<<"$asset")"
    sha="$(jq -r '.digest // ""' <<<"$asset" | sed 's/^sha256://')"
    url="https://github.com/$OWNER/$REPO/releases/download/$TAG_NAME/$name"
    human="$(awk -v n="$size" 'BEGIN { if (n >= 1048576) printf "%.1f MB", n / 1048576; else printf "%.0f KB", n / 1024 }')"
    if [ -n "$MANIFEST" ]; then
      msha="$(jq -r --arg p "$platform" '.[$p].stable.sha256 // empty' <<<"$MANIFEST" 2>/dev/null || true)"
      masset="$(jq -r --arg p "$platform" '.[$p].stable.asset // empty' <<<"$MANIFEST" 2>/dev/null || true)"
      if [ -n "$msha" ] && [ "$masset" = "$name" ] && [ "$msha" != "$sha" ]; then
        echo "warning: $name — GitHub says sha256 $sha, the release manifest says $msha" >&2
      fi
    fi
    printf '          <tr>\n'
    printf '            <td><span class="pill">%s</span></td>\n' "$label"
    printf '            <td class="name"><a href="%s">%s</a></td>\n' "$url" "$name"
    printf '            <td class="sz">%s</td>\n' "$human"
    if [ -z "$sha" ]; then
      # The app will download such an asset but refuse to run it; the page has to
      # say that rather than show a confident-looking empty column.
      printf '            <td><span class="sha">no sha256 published — the app will not run this one</span></td>\n'
      printf '            <td></td>\n          </tr>\n'
    else
      printf '            <td><span class="sha">%s</span></td>\n' "$sha"
      printf '            <td><button class="copy" data-copy="%s">copy</button></td>\n          </tr>\n' "$sha"
    fi
  done <<<"$ROWS"
} >"$tmp"

awk -v rows="$tmp" '
  /<!-- BEGIN ASSETS -->/ { print; while ((getline l < rows) > 0) print l; skip = 1; close(rows); next }
  /<!-- END ASSETS -->/   { skip = 0; print; next }
  skip                     { next }
  !skip                    { print }
' "$FILE" >"$out"

# Only the two unambiguous version statements in the page are rewritten. The
# prose ("Download v0.3.0" and its Persian twin) is a human's sentence, and a
# generator that rewrites prose is how a page ends up reading like a changelog.
sed -e "s|<caption>v[0-9][0-9.]* · |<caption>v$VERSION · |" \
    -e "s|id=\"ver\">v[0-9][0-9.]*<|id=\"ver\">$TAG_NAME<|" \
    -e "s|releases/tag/v[0-9][0-9.]*|releases/tag/$TAG_NAME|" \
    -e "s|releases/download/v[0-9][0-9.]*/SHA256SUMS.txt|releases/download/$TAG_NAME/SHA256SUMS.txt|" \
    "$out" >"$out.2" && mv "$out.2" "$out"
# Every table row and the caption are kept in sync above; a download link
# anywhere else in the page is a copy a human made, and copies are what go stale.
stray="$(grep -n 'releases/download/v[0-9][0-9.]*/' "$out" | grep -v '<td class="name">' | grep -v '<caption>' || true)"
if [ -n "$stray" ]; then
  echo "warning: download links outside the table will not be updated by this script:" >&2
  printf '%s\n' "$stray" | sed 's/^/  /' >&2
fi

rows_now="$(grep -c '<tr' "$out")"
[ "$rows_now" -ge 3 ] || { echo "refusing to write a table with $rows_now rows" >&2; exit 1; }

if [ "$CHECK" = 1 ]; then
  if cmp -s "$out" "$FILE"; then
    echo "$FILE is current for $TAG_NAME"
  else
    echo "::error::$FILE is out of date for $TAG_NAME — run scripts/gen_site_index.sh" >&2
    diff -u "$FILE" "$out" | head -60 >&2 || true
    exit 1
  fi
else
  cp "$out" "$FILE"
  echo "wrote $FILE ($rows_now rows for $TAG_NAME)"
fi
