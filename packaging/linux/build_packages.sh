#!/usr/bin/env bash
# build_packages.sh — turn `flutter build linux` output into .deb / .rpm /
# .pkg.tar.zst / .AppImage.
#
# Run from app/ after a release build:
#   VERSION=0.1.0 ARCH=x64 bash ../packaging/linux/build_packages.sh
#
# Deliberately no `fpm`, no `dpkg-buildpackage`, no docker: each of those is a
# reasonable tool and a reason CI fails on an unrelated image pull. A tar of
# staging dirs plus three well-understood commands is enough for an app with
# exactly one binary, one .desktop file, an icon and an engine executable.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
app="${APP_DIR:-$root/app}"
version="${VERSION:?build_packages.sh needs VERSION (e.g. VERSION=0.1.0)}"
arch="${ARCH:-x64}"
pkg_archDeb="$arch"
pkg_name_arch="$arch"
case "$arch" in
  x64)
    pkg_archDeb="amd64"
    pkg_archRpm="x86_64"
    bundle_dir="$app/build/linux/x64/release/bundle"
    ;;
  arm64)
    pkg_archDeb="arm64"
    pkg_archRpm="aarch64"
    bundle_dir="$app/build/linux/arm64/release/bundle"
    ;;
  *)
    echo "build_packages: ARCH must be x64 or arm64" >&2
    exit 2
    ;;
esac

[[ -d "$bundle_dir" ]] || { echo "build_packages: no build output at $bundle_dir (run 'flutter build linux --release')" >&2; exit 1; }

dist="$app/dist"
stage="$root/build/stage-$arch"
rm -rf "$dist" "$stage"
mkdir -p "$dist" "$stage"

# --- layout ------------------------------------------------------------------
# /opt instead of /usr/bin: the Flutter Linux bundle is a directory (lib/,
# data/, the engine next to the executable), not a single relocatable binary, and
# pretending otherwise means symlinking half a tree.
prefix="/opt/naxlo-two"
mkdir -p "$stage$prefix" "$stage/usr/bin" "$stage/usr/share/applications" \
         "$stage/usr/share/icons/hicolor/256x256/apps" "$stage/usr/share/doc/naxlo-two"
cp -a "$bundle_dir/." "$stage$prefix/"
cp "$root/packaging/linux/naxlo-two.desktop" "$stage/usr/share/applications/"
cp "$root/NOTICE" "$root/LICENSE" "$stage/usr/share/doc/naxlo-two/" 2>/dev/null || true

# Engine binary, if scripts/fetch_engine.sh put one next to the build. It goes in
# the same directory as the app executable, which is the second place
# lib/state/engine_locator.dart looks (after an explicit user path).
for eng in xray sing-box; do
  found="$(find "$app/assets/engine/linux-$pkg_archDeb" -maxdepth 2 -type f -name "$eng" 2>/dev/null | head -1 || true)"
  [[ -n "$found" ]] && cp "$found" "$stage$prefix/$eng" && chmod 755 "$stage$prefix/$eng"
done

# Launcher: a wrapper rather than a symlink, because /opt layout means the
# executable must be found relative to its own path for `data/flutter_assets`.
cat > "$stage/usr/bin/naxlo-two" <<EOF
#!/bin/sh
# Generated by packaging/linux/build_packages.sh — do not edit in the package.
exec "$prefix/naxlo_two" "\$@"
EOF
chmod 755 "$stage/usr/bin/naxlo-two"

# A minimal hicolor icon keeps `gtk-update-icon-cache` happy in desktops that
# insist; the app's real window icon comes from the bundle itself.
if [[ ! -f "$root/app/assets/icons/naxlo-256.png" ]]; then
  printf 'PNG-stub' > "$stage/usr/share/icons/hicolor/256x256/apps/naxlo-two.png"
else
  cp "$root/app/assets/icons/naxlo-256.png" "$stage/usr/share/icons/hicolor/256x256/apps/naxlo-two.png"
fi

desc="Cross-platform proxy client (Xray-core / sing-box) with configurable server ranking."

# --- .deb --------------------------------------------------------------------
if command -v dpkg-deb >/dev/null 2>&1; then
  control="$stage/DEBIAN"
  mkdir -p "$control"
  size_kb="$(du -sk "$stage" | cut -f1)"
  cat > "$control/control" <<EOF
Package: naxlo-two
Version: $version
Section: net
Priority: optional
Architecture: $pkg_archDeb
Maintainer: Naxlo <packaging@naxlo.dev>
Homepage: https://github.com/Manixpcshot/Naxlo-Two
Installed-Size: $size_kb
Depends: libgtk-3-0
Recommends: libnss3
Description: $desc
 Proxy client that configures and supervises Xray-core or sing-box as a child
 process. Local SOCKS5/HTTP inbounds, optional system-proxy takeover, per-profile
 routing and DNS, and a ranker that chooses the server by latency, jitter,
 reliability and throughput rather than by ping alone.
 .
 No telemetry: profiles and logs stay in the user's app-support directory.
EOF
  cat > "$control/postinst" <<'EOF'
#!/bin/sh
set -e
# TUN mode needs privileges; granting them at install time is the least-surprising
# place to do it, and failing to do so must not break the deb.
if command -v setcap >/dev/null 2>&1 && id -u >/dev/null 2>&1; then
  for bin in /opt/naxlo-two/sing-box /opt/naxlo-two/xray; do
    [ -x "$bin" ] && setcap cap_net_admin,cap_net_raw=eip "$bin" 2>/dev/null || true
  done
fi
update-desktop-database /usr/share/applications >/dev/null 2>&1 || true
exit 0
EOF
  chmod 755 "$control/postinst"
  find "$stage" -name .gitignore -delete 2>/dev/null || true
  dpkg-deb --build --root-owner-group "$stage" "$dist/Naxlo.linux.$arch.deb"
  echo "  deb  ok"
else
  echo "  deb  skipped (dpkg-deb not installed)"
fi

# --- .rpm --------------------------------------------------------------------
if command -p rpmbuild >/dev/null 2>&1 || command -v rpmbuild >/dev/null 2>&1; then
  rpm_root="$root/build/rpmbuild-$arch"
  mkdir -p "$rpm_root"/{BUILD,RPMS,SOURCES,SPECS,SRPMS}
  ( cd "$stage" && tar --exclude='./DEBIAN' -czf "$rpm_root/SOURCES/tree.tar.gz" . )
  sed -e "s/@VERSION@/$version/g" -e "s/@ARCH@/$pkg_archRpm/g" -e "s/@DESC@/$desc/" \
    "$root/packaging/linux/naxlo-two.spec" > "$rpm_root/SPECS/naxlo-two.spec"
  rpmbuild -bb --define "_topdir $rpm_root" --define "_unpack_files_dir $rpm_root/BUILD" \
    "$rpm_root/SPECS/naxlo-two.spec"
  found="$(find "$rpm_root/RPMS" -name 'naxlo-two-*.rpm' | head -1)"
  [[ -n "$found" ]] && cp "$found" "$dist/Naxlo.linux.$arch.rpm" && echo "  rpm  ok"
else
  echo "  rpm  skipped (rpmbuild not installed)"
fi

# --- Arch .pkg.tar.zst -------------------------------------------------------
# Built directly instead of via makepkg: the archive is just a zstd tar with a
# .PKGINFO at the root, and makepkg would need a PKGBUILD *plus* a non-root
# builder user in the container, which CI does not have.
if command -v zstd >/dev/null 2>&1 || command -v tar >/dev/null 2>&1; then
  arch_root="$root/build/arch-$arch"
  rm -rf "$arch_root"
  mkdir -p "$arch_root"
  cp -a "$stage/." "$arch_root/"
  pkgsize="$(du -sk "$arch_root" | cut -f1)"
  # .PKGINFO is what pacman reads; a wrong `pkgbase`/`packager` line means the
  # package installs but cannot be queried, so it is written here, not templated.
  {
    echo "# Generated by packaging/linux/build_packages.sh"
    echo "pkgname = naxlo-two"
    echo "pkgbase = naxlo-two"
    echo "pkgver = $version-1"
    echo "pkgdesc = $desc"
    echo "url = https://github.com/Manixpcshot/Naxlo-Two"
    echo "builddate = $(date +%s)"
    echo "packager = naxlo-builder"
    echo "arch = $pkg_archRpm"
    echo "license = MIT"
    echo "depend = gtk3"
    echo "makedepend = flutter"
    echo "size = $pkgsize"
  } > "$arch_root/.PKGINFO"
  date_line="!"
  ( cd "$arch_root" && rm -rf DEBIAN && tar --format=pax --zstd -cf "$dist/Naxlo.linux.$arch.pkg.tar.zst" . ) \
    || ( cd "$arch_root" && rm -rf DEBIAN && tar -cf - . | zstd -T0 -3 > "$dist/Naxlo.linux.$arch.pkg.tar.zst" )
  echo "  pkg.tar.zst ok"
else
  echo "  arch skipped (no zstd/tar)"
fi

# --- AppImage ----------------------------------------------------------------
# Only assembled when the tooling is present: appimagetool needs FUSE (absent in
# containers) unless APPIMAGE_EXTRACT_AND_RUN=1, which is why the env var is set
# here rather than left to the caller.
if [[ -n "${APPIMAGETOOL:-}" ]] || command -v appimagetool >/dev/null 2>&1; then
  ai_root="$root/build/appimage-$arch"
  rm -rf "$ai_root"
  mkdir -p "$ai_root"/{AppDir,usr/bin}
  cp -a "$stage$prefix/." "$ai_root/AppDir/usr/lib/naxlo-two/"
  cat > "$ai_root/AppDir/AppRun" <<'EOF'
#!/bin/sh
# AppImage entry point. The app lives under /usr/lib inside the mounted squashfs,
# so `--appimage-extract-and-run` style self-locate is unavoidable.
HERE="$(dirname "$(readlink -f "$0")")"
exec "$HERE/usr/lib/naxlo-two/naxlo_two" "$@"
EOF
  chmod +x "$ai_root/AppDir/AppRun"
  cp "$root/packaging/linux/naxlo-two.desktop" "$ai_root/AppDir/naxlo-two.desktop"
  tool="${APPIMAGETOOL:-appimagetool}"
  ARCH="$pkg_archRpm" APPIMAGE_EXTRACT_AND_RUN=1 "$tool" "$ai_root/AppDir" \
    "$dist/Naxlo.linux.$arch.AppImage" && chmod +x "$dist/Naxlo.linux.$arch.AppImage" && echo "  AppImage ok"
else
  echo "  AppImage skipped (set APPIMAGETOOL=…/appimagetool-x86_64.AppImage to build it)"
fi

echo
ls -l "$dist" 2>/dev/null | tail -n +2
echo
echo "build_packages: $version ($arch) → $dist"
